"""Extract the REAL schema objects needed for the isolated support/WhatsApp fixture (read-only catalog queries).

Usage: python3 supabase/tests/support_fixture_extract.py > /tmp/supfx/schema.sql
Only DDL from the catalog is read; no row data is exported. Load into an isolated local Postgres only.
"""
import subprocess

TABLES = [
    "public.user_roles", "public.members_data", "public.member_profiles", "public.internal_projects",
    "public.whatsapp_conversations", "public.whatsapp_messages", "public.whatsapp_webhook_events",
    "public.whatsapp_announcement_publishers", "public.whatsapp_announcement_decisions",
    "public.member_announcements", "public.member_announcement_attachments",
    "public.whatsapp_member_links", "public.whatsapp_link_codes", "public.whatsapp_link_attempts",
    "public.support_threads", "public.support_messages", "public.support_attachments",
    "storage.objects",
]
FUNC_LIKE = "proname LIKE 'support\\_%' OR proname LIKE 'whatsapp\\_%' OR proname IN ('has_role','get_member_project_status','member_verloop_items','update_updated_at_column','prepare_member_announcement')"
# Side-effecting notifiers are replaced by inert stubs (they are not under test and may reach the network).
STUB_TRIGGERS = {"notify_members_on_published_announcement", "zz_announcement_sync_projects"}
TRIGGER_TABLES = ["public.whatsapp_messages", "public.whatsapp_conversations", "public.member_announcements",
                  "public.support_threads", "public.support_messages", "public.support_attachments"]


def q(sql):
    return subprocess.run(["psql", "-AtX", "-F", "\x1f", "-R", "\x1e", "-c", sql], capture_output=True, text=True, check=True).stdout.rstrip("\x1e\n").split("\x1e") if sql else []


def rows(sql):
    return [r.lstrip("\n").split("\x1f") for r in q(sql) if r.strip()]


out = ["-- GENERATED from live catalog (DDL only, no data).", "SET check_function_bodies = off;",
       "CREATE SCHEMA IF NOT EXISTS extensions; CREATE EXTENSION IF NOT EXISTS pgcrypto SCHEMA extensions;",
       "CREATE SCHEMA IF NOT EXISTS auth; CREATE SCHEMA IF NOT EXISTS storage;",
       "DO $$BEGIN CREATE ROLE anon; EXCEPTION WHEN duplicate_object THEN NULL; END$$;",
       "DO $$BEGIN CREATE ROLE authenticated; EXCEPTION WHEN duplicate_object THEN NULL; END$$;",
       "DO $$BEGIN CREATE ROLE service_role; EXCEPTION WHEN duplicate_object THEN NULL; END$$;",
       "GRANT USAGE ON SCHEMA public, auth, storage, extensions TO anon, authenticated, service_role;",
       "CREATE TABLE auth.users(id uuid PRIMARY KEY, email text);",
       # Same semantics as Supabase auth helpers: identity comes only from request.jwt.claims.
       "CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claims', true)::json->>'sub','')::uuid $$;",
       "CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$ SELECT current_setting('request.jwt.claims', true)::json->>'role' $$;",
       "GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA auth TO anon, authenticated, service_role;"]

for name, labels in rows("select t.typname, string_agg(quote_literal(e.enumlabel), ',' order by e.enumsortorder) from pg_type t join pg_enum e on e.enumtypid=t.oid where t.typnamespace='public'::regnamespace group by 1"):
    out.append(f"CREATE TYPE public.{name} AS ENUM ({labels});")

for fn in rows("select pg_get_functiondef(p.oid) from pg_proc p where p.pronamespace='storage'::regnamespace and proname in ('foldername','extension','filename')"):
    out.append(fn[0].strip() + ";")

tset = set(TABLES)
for t in TABLES:
    cols = rows(f"select quote_ident(attname), format_type(atttypid, atttypmod), coalesce(pg_get_expr(d.adbin,d.adrelid),''), attnotnull, attidentity, attgenerated from pg_attribute a left join pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum where attrelid='{t}'::regclass and attnum>0 and not attisdropped order by attnum")
    parts = []
    for c, typ, df, nn, ident, gen in cols:
        s = f"{c} {typ}"
        if ident:
            s += " GENERATED ALWAYS AS IDENTITY" if ident == "a" else " GENERATED BY DEFAULT AS IDENTITY"
        elif gen == "s":
            s += f" GENERATED ALWAYS AS ({df}) STORED"
        elif df:
            s += f" DEFAULT {df}"
        if nn == "t":
            s += " NOT NULL"
        parts.append(s)
    out.append(f"CREATE TABLE {t} (\n  " + ",\n  ".join(parts) + "\n);")

for t in TABLES:
    for cname, cdef, ctype, ref in rows(f"select conname, pg_get_constraintdef(oid), contype, coalesce(confrelid::regclass::text,'') from pg_constraint where conrelid='{t}'::regclass order by contype desc"):
        if ctype == "f":
            r = ref if "." in ref else "public." + ref
            if r not in tset:
                continue
        out.append(f"ALTER TABLE {t} ADD CONSTRAINT {cname} {cdef};")
    for (idx,) in rows(f"select indexdef from pg_indexes i where schemaname||'.'||tablename='{t}' and not exists(select 1 from pg_constraint c where c.conname=i.indexname)"):
        out.append(idx + ";")

for (fn,) in rows(f"select pg_get_functiondef(p.oid) from pg_proc p where p.pronamespace='public'::regnamespace and ({FUNC_LIKE}) order by proname"):
    out.append(fn.strip() + ";")
out.append("CREATE OR REPLACE FUNCTION public.notify_members_on_published_announcement() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$; -- inert stub")
out.append("CREATE OR REPLACE FUNCTION public.announcement_sync_projects_trigger() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$; -- inert stub")

for t in TRIGGER_TABLES:
    for name, tdef in rows(f"select tgname, pg_get_triggerdef(oid) from pg_trigger where tgrelid='{t}'::regclass and not tgisinternal"):
        out.append(tdef + ";")

for t in TABLES:
    if rows(f"select 1 from pg_class where oid='{t}'::regclass and relrowsecurity"):
        out.append(f"ALTER TABLE {t} ENABLE ROW LEVEL SECURITY;")
    flt = "and (policyname ilike '%support%')" if t == "storage.objects" else ""
    for name, perm, roles, cmd, using, check in rows(f"select policyname, permissive, array_to_string(roles, ','), cmd, coalesce(qual,''), coalesce(with_check,'') from pg_policies where schemaname||'.'||tablename='{t}' {flt}"):
        s = f'CREATE POLICY "{name}" ON {t} AS {perm} FOR {cmd} TO {roles}'
        if using:
            s += f" USING ({using})"
        if check:
            s += f" WITH CHECK ({check})"
        out.append(s + ";")
    for grantee, privs in rows(f"select r.rolname, string_agg(a.privilege_type, ', ') from pg_class c, aclexplode(c.relacl) a join pg_roles r on r.oid=a.grantee where c.oid='{t}'::regclass and r.rolname in ('anon','authenticated','service_role') group by 1"):
        out.append(f"GRANT {privs} ON {t} TO {grantee};")

out.append("REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA public FROM PUBLIC;")
for sig, grantee in rows(f"select p.oid::regprocedure, r.rolname from pg_proc p, aclexplode(p.proacl) a join pg_roles r on r.oid=a.grantee where p.pronamespace='public'::regnamespace and ({FUNC_LIKE}) and r.rolname in ('anon','authenticated','service_role')"):
    out.append(f"GRANT EXECUTE ON FUNCTION {sig} TO {grantee};")
for sig in rows(f"select p.oid::regprocedure from pg_proc p where p.pronamespace='public'::regnamespace and ({FUNC_LIKE}) and (p.proacl is null or exists(select 1 from aclexplode(p.proacl) a where a.grantee=0))"):
    out.append(f"GRANT EXECUTE ON FUNCTION {sig[0]} TO PUBLIC;")
print("\n".join(out))
